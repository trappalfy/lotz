export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Rows of one glyph (always 7 rows of 5 cells; unknown characters are blank). */
export function glyph(ch: string): boolean[][] {
  const rows = G[ch] ?? G[ch.toLowerCase()] ?? G[" "]!;
  return rows.map((r) => [...r].map((c) => c === "#"));
}

/** A string as a cell matrix, one empty column between glyphs. */
export function textCells(text: string): boolean[][] {
  const glyphs = [...text].map(glyph);
  const width = glyphs.length * (GLYPH_W + 1) - 1;
  const rows: boolean[][] = Array.from({ length: GLYPH_H }, () => Array(Math.max(0, width)).fill(false));
  glyphs.forEach((g, i) => {
    for (let y = 0; y < GLYPH_H; y++) for (let x = 0; x < GLYPH_W; x++) rows[y]![i * (GLYPH_W + 1) + x] = g[y]![x]!;
  });
  return rows;
}

/** Every glyph is 7 rows of 5 cells (checked by the tests). */
export function glyphTableValid(): boolean {
  return Object.values(G).every((rows) => rows.length === GLYPH_H && rows.every((r) => r.length === GLYPH_W));
}
